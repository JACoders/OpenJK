"""Network field descriptors from one source of truth (PLAN.md step 2).

The source is codemp/qcommon/msg.cpp. Offsets, sizes and macro widths are computed by a C++ compiler:

1. python gen_fields.py              writes ../fieldinfo/fields.inc from msg.cpp
2. build ../fieldinfo with CMake (it compiles fields.inc against codemp/qcommon/q_shared.h)
3. python gen_fields.py --exe PATH   runs the program, checks it against fields.inc, writes ../../data/fields.json

`bits` is the width msg.cpp sends today (0 = float coding); `type` is the C type of the field (bool for qboolean,
int, float, enum). They differ for the mod fields user*: declared 1 bit wide whatever their type.
The schema hash covers table order, names, widths, types and arrays, not the offsets.
"""
import re, os, sys, json, hashlib, subprocess, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))
SRC = os.path.join(ROOT, "codemp", "qcommon", "msg.cpp")
INC = os.path.normpath(os.path.join(HERE, "..", "fieldinfo", "fields.inc"))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "data", "fields.json"))
SCHEMA_VERSION = 2   # 2: C type per field

# key, array name in msg.cpp, struct. The first playerStateFields is the _OPTIMIZED_VEHICLE_NETWORKING one
# (q_shared.h defines it); the second, under #else, is not compiled.
TABLES = (("ent", "entityStateFields", "entityState_t"),
          ("ps", "playerStateFields", "playerState_t"),
          ("pilot", "pilotPlayerStateFields", "playerState_t"),
          ("veh", "vehPlayerStateFields", "playerState_t"))
# The four playerState_t arrays sent after the fields (MSG_WriteDeltaPlayerstate): count macro and value width,
# -16 = MSG_WriteShort, -32 = MSG_WriteLong. stats[STAT_WEAPONS] is sent in MAX_WEAPONS bits instead.
ARRAYS = (("stats", "MAX_STATS", -16), ("persistant", "MAX_PERSISTANT", -16),
          ("ammo", "MAX_AMMO_TRANSMIT", -16), ("powerups", "MAX_POWERUPS", -32))


def parse_msg(src):
    """Field entries of the four tables, widths as written in the source (a number or a macro)."""
    out = {}
    for key, name, _ in TABLES:
        idx = re.search(r"netField_t\s+" + name + r"\[\]\s*=", src).start()
        body = src[idx:src.index("\n};", idx)]
        body = re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", body), flags=re.S)
        out[key] = re.findall(r"\{\s*(?:NETF|PSF)\((.+?)\),\s*([-\w]+)\s*\}", body)
    stat_weapons = re.search(r"#define\s+STAT_WEAPONS\s+(\d+)", src).group(1)
    return out, stat_weapons


def write_inc(tables, stat_weapons):
    L = ["// Generated by docs_rewrite/netcode/tools/python/gen_fields.py from codemp/qcommon/msg.cpp. Do not edit.",
         "#define STAT_WEAPONS %s  // msg.cpp defines it locally" % stat_weapons,
         "S(entityState_t)", "S(playerState_t)", "C(MAX_WEAPONS)", "C(STAT_WEAPONS)"]
    for name, count, _ in ARRAYS:
        L.append("A(%s, %s)" % (name, count))
    for key, _, struct in TABLES:
        for fname, bits in tables[key]:
            L.append("F(%s, %s, %s, %s)" % (key, struct, fname, bits))
    with open(INC, "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")


def build_json(tables, exe):
    lines = subprocess.run([exe], capture_output=True, text=True, check=True).stdout.splitlines()
    sizes, consts, arrays, fields = {}, {}, {}, {k: [] for k, _, _ in TABLES}
    for l in lines:
        p = l.split("\t")
        if p[0] == "S": sizes[p[1]] = int(p[2])
        elif p[0] == "C": consts[p[1]] = int(p[2])
        elif p[0] == "A": arrays[p[1]] = dict(count=int(p[2]), offset=int(p[3]), elem_size=int(p[4]))
        elif p[0] == "F":
            if len(p) != 7: raise SystemExit("%s: no type column; rebuild the program" % exe)
            fields[p[1]].append(dict(name=p[2], bits=int(p[3]), type=p[6], offset=int(p[4]), size=int(p[5])))
        else: raise ValueError("unexpected line from %s: %r" % (exe, l))
    for key, _, _ in TABLES:
        if [f["name"] for f in fields[key]] != [n for n, b in tables[key]]:
            raise SystemExit("%s: table %s differs from fields.inc; rebuild the program" % (exe, key))
        for f in fields[key]:
            assert f["size"] == 4, f        # the engine reads every field as one 32-bit word
            assert f["type"] != "?", f      # a type TypeName() in fieldinfo.cpp does not know
    arr = []
    for name, _, bits in ARRAYS:
        a = dict(name=name, bits=bits, **arrays[name])
        if name == "stats":
            a["special"] = dict(index=consts["STAT_WEAPONS"], bits=consts["MAX_WEAPONS"])
        arr.append(a)
    wire = dict(tables={k: [[f["name"], f["bits"], f["type"]] for f in v] for k, v in fields.items()},
                arrays=[[a["name"], a["count"], a["bits"], a.get("special")] for a in arr])
    h = hashlib.sha256(json.dumps(wire, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    return dict(schema_version=SCHEMA_VERSION, schema_hash=h, source="codemp/qcommon/msg.cpp",
                sizeof=sizes, tables=fields, arrays=arr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", help="built fieldinfo program; without it only fields.inc is written")
    a = ap.parse_args()
    tables, sw = parse_msg(open(SRC, encoding="latin-1").read())
    write_inc(tables, sw)
    print("fields.inc:", ", ".join("%s %d" % (k, len(v)) for k, v in tables.items()))
    if a.exe:
        d = build_json(tables, a.exe)
        with open(OUT, "w", newline="\n") as f:
            json.dump(d, f, indent=1)
            f.write("\n")
        print("fields.json: schema %d, hash %s" % (d["schema_version"], d["schema_hash"]))
        for k, v in d["tables"].items():
            n = {}
            for f in v: n[f["type"]] = n.get(f["type"], 0) + 1
            odd = ["%s(%s,%d)" % (f["name"], f["type"], f["bits"]) for f in v
                   if (f["type"] == "bool") != (f["bits"] == 1) or (f["type"] == "float") != (f["bits"] == 0)]
            print("  %s types %s; width not matching type: %s" % (k, n, " ".join(odd) or "none"))


if __name__ == "__main__":
    main()
