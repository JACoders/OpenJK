"""Step 6: generate the C++ schema and tables of codemp/netcodec from the Python reference codec.

Inputs: data/fields.json (field list, widths, C types, offsets), the codec field order of codec.py / codec2.py (with
the prediction order), and the product tables of train_tables.py (data/traces/tables.pkl).
Output: codemp/netcodec/src/generated/jka_codec.inc (committed; regenerate after a change of the fields, the codec or the
training). Every context the C++ codec can ask for gets a table: trained ones as trained, the others with the
uniform table Python's Tables gives for that alphabet size, so the C++ needs no fallback and stays byte-identical.
Run: python gen_netcodec.py"""
import sys, os, pickle, hashlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import codec as C, codec2 as K2

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.normpath(os.path.join(HERE, "..", "..", "data", "traces", "tables.pkl"))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "codemp", "netcodec", "src", "generated", "jka_codec.inc"))

# per-field context kinds, in the order of the C++ enum FieldCtx
KINDS = ["a", "d", "k", "ia", "id", "ad", "fd", "t", "fp", "a2", "b"]
PMODE = {None: 0, "t": 1, "pi": 2, "a2": 3}
CTYPE = {"int": 0, "float": 1, "bool": 2, "enum": 3}
NCLS = 19
# scalar contexts: (name in C++, Python context, alphabet size)
SCALARS = [("kMDelta", ("m", "delta"), 256), ("kMAck", ("m", "ack"), 36), ("kMCmdSeq", ("m", "cseq"), 36),
           ("kMRelSeq", ("m", "rseq"), 36), ("kMNumCs", ("m", "ncs"), 16), ("kMCsGap", ("m", "csgap"), 16),
           ("kMClientNum", ("m", "cnum"), 36), ("kMDlBlock", ("m", "dlblk"), 20), ("kMDlSize", ("m", "dlsize"), 36),
           ("kMDlLen", ("m", "dllen"), 20), ("kDlByte", ("dl",), 256), ("kHTime", ("h", "time"), 36),
           ("kHFlags", ("h", "flags"), 256), ("kHArea", ("h", "area"), 256), ("kPsPilot", ("ps", "pilot"), 2),
           ("kStrCmd", ("str", "cmd"), 256), ("kStrSetgame", ("str", "sg"), 256), ("kStrCs", ("str", "cs"), 256),
           ("kEntGap", ("eg",), 42)]

def kind_size(kind, bits):
    ab = abs(bits)
    return {"a": (1 << ab) if ab <= 8 else ab + 2, "d": ab + 2, "k": 4, "ia": 16, "id": 16, "ad": 24, "fd": 36,
            "t": 36, "fp": 36, "a2": 40, "b": 2}[kind]

def kinds_of(bits, ctype):
    """contexts a field can use: integers a / d (and t), floats k / ia / id / ad / fd (and fp, a2), booleans b too"""
    ks = {"a", "d", "t"} if bits != 0 else {"k", "ia", "id", "ad", "fd", "fp", "a2"}
    if ctype == "bool": ks.add("b")
    return ks

def main():
    K2.enable_prediction()
    tr = pickle.load(open(TABLES, "rb"))
    tables = C.Tables(tr["counts"], tr["alpha"])
    modes, pmodes = tr["modes"], tr["pmodes"]
    fields = C.B.bdata.J.FIELDS
    off = {("e:", f["name"]): f["offset"] for f in fields["tables"]["ent"]}
    for tn in ("ps", "pilot", "veh"):
        for f in fields["tables"][tn]: off[("p:", f["name"])] = f["offset"]
    for a in fields["arrays"]:
        for i in range(a["count"]): off[("p:", "%s[%d]" % (a["name"], i))] = a["offset"] + i * a["elem_size"]

    freqs = []; index = {}
    def tid(ctx, K):
        f = tuple(tables.table(ctx, K)[0])
        assert sum(f) == 1 << C.PB
        if f not in index: index[f] = len(freqs); freqs.append(f)
        return index[f]

    ent = C.EF; pnames = K2.ALLNAMES; pid = {n: i for i, n in enumerate(pnames)}
    pbits = {}
    for t in K2.PS_TABLES.values():
        for n, b in t:
            assert pbits.setdefault(n, b) == b, n
    def field_ctx(pre, name, bits):
        cn = pre + name; ks = kinds_of(bits, C.CTYPE.get(cn, "int"))
        return [tid((cn, k), kind_size(k, bits)) if k in ks else 0xFFFF for k in KINDS]

    lines = []; w = lines.append
    w("// Generated by docs_rewrite/netcode/tools/python/gen_netcodec.py: do not edit.")
    w("// Schema (codec field order) and trained tables of the JKA codec; see docs_rewrite/netcode/progress/step-06-cpp-codec.md.")
    w("")
    def related(pre, name):
        """offsets read by the position prediction of a field, else 0xFFFF"""
        if pmodes.get(pre + name) != "pi": return (0xFFFF, 0xFFFF, 0xFFFF, 0xFFFF)
        i = name[-2]
        if pre == "e:":
            return (off[("e:", "pos.trType")], off[("e:", "pos.trTime")], off[("e:", "pos.trDelta[%s]" % i)], 0)
        return (0xFFFF, off[("p:", "commandTime")], off[("p:", "velocity[%s]" % i)], 1)
    def desc(pre, name, bits, ctx_id):
        cn = pre + name; rel = related(pre, name)
        return ("\t{ .offset = %d, .bits = %d, .ctype = %d, .absolute = %d, .pmode = %d, .ctx = %d, .relType = %d, "
                ".relTime = %d, .relVel = %d, .relKind = %d }, // %s") % (
            off[(pre, name)], bits, CTYPE[C.CTYPE.get(cn, "int")], 1 if modes.get(name, "d") == "a" else 0,
            PMODE[pmodes.get(cn)], ctx_id, rel[0], rel[1], rel[2], rel[3], name)
    w("inline constexpr uint32_t kEntitySize = %d;" % fields["sizeof"]["entityState_t"])
    w("inline constexpr uint32_t kPlayerSize = %d;" % fields["sizeof"]["playerState_t"])
    w("inline constexpr uint32_t kEntityTypeIndex = %d;   // eType, coded apart" % C.ET_IDX)
    w("inline constexpr uint32_t kEntityClasses = %d;" % NCLS)
    w("inline constexpr uint32_t kPlayerNames = %d;" % len(pnames))
    for nm, cname in (("m_iVehicleNum", "kVehicleNum"), ("eFlags", "kPlayerEFlags")):
        w("inline constexpr uint16_t %sOffset = %d;   // bits %d" % (cname, off[("p:", nm)], pbits[nm]))
    w("")
    w("// FieldDesc: offset, bits (0 float, < 0 signed), C type, absolute mode, prediction mode, context row, then for")
    w("// the position prediction the offsets of trType, time, velocity and the kind (0 entity, 1 player state)")
    w("inline constexpr std::array<FieldDesc, %d> kEntityFields{ {" % len(ent))
    for i, (n, b) in enumerate(ent): lines.append(desc("e:", n, b, i))
    w("} };")
    for tab, label in ((0, "kPlayerFields"), (1, "kPilotFields"), (2, "kVehicleFields")):
        w("inline constexpr std::array<FieldDesc, %d> %s{ {" % (len(K2.PS_TABLES[tab]), label))
        for n, b in K2.PS_TABLES[tab]: lines.append(desc("p:", n, b, pid[n]))
        w("} };")
    w("// offsets of every player-state field (union of the three tables): 'has a base' test of the prediction")
    w("inline constexpr std::array<uint16_t, %d> kPlayerAllOffsets{ %s };" % (len(pnames), ", ".join(str(off[("p:", n)]) for n in pnames)))
    w("")
    ectx = [field_ctx("e:", n, b) for n, b in ent]
    pctx = [field_ctx("p:", n, pbits[n]) for n in pnames]
    def arr1(name, vals):
        w("inline constexpr std::array<uint16_t, %d> %s{ %s };" % (len(vals), name, ", ".join(str(x) for x in vals)))
    def arr2(name, rows):
        w("inline constexpr std::array<std::array<uint16_t, %d>, %d> %s{ {" % (len(rows[0]), len(rows), name))
        for r in rows: w("\t{ %s }," % ", ".join(str(x) for x in r))
        w("} };")
    arr2("kEntityFieldCtx", ectx); arr2("kPlayerFieldCtx", pctx)
    for tab in (0, 1, 2):
        n = len(K2.PS_TABLES[tab])
        arr1("kPlayerGapCtx%d" % tab, [tid(("pg", tab, p), n + 1) for p in range(-1, n)])
    NE = len(ent)
    arr2("kEntityGapCtx", [[tid(("eg2", c, p), NE + 1) for p in range(-1, NE)] for c in range(NCLS)])
    arr1("kEntityOpCtx", [tid(("eo", p), 4) for p in range(4)])
    arr1("kTypeChangedCtx", [tid(("ef", "et", c), 2) for c in range(NCLS)])
    arr1("kTypeValueCtx", [tid(("ev", "et", c), 256) for c in range(NCLS)])
    arr1("kOpCtx", [tid(("op", p), 8) for p in range(8)])
    for name, ctx, K in SCALARS: w("inline constexpr uint16_t %s = %d;" % (name, tid(ctx, K)))
    w("")
    w("inline constexpr uint32_t kTableCount = %d;" % len(freqs))
    starts = []; s = 0
    for f in freqs: starts.append(s); s += len(f)
    w("inline constexpr std::array<uint32_t, %d> kTableStart{ %s };" % (len(freqs) + 1, ", ".join(str(x) for x in starts + [s])))
    w("inline constexpr std::array<uint16_t, %d> kFreq{" % s)
    flat = [x for f in freqs for x in f]
    for i in range(0, len(flat), 24): w("\t" + ", ".join(str(x) for x in flat[i:i + 24]) + ",")
    w("};")
    text = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s: %d tables (%d trained contexts), %d frequencies, sha1 %s" % (
        OUT, len(freqs), len(tr["counts"]), s, hashlib.sha1(text.encode()).hexdigest()[:12]))

if __name__ == "__main__":
    main()
