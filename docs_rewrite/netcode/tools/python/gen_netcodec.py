"""Step 6: generate the C++ schema of codemp/netcodec.

Inputs: data/fields.json (field list, widths, C types, offsets), the codec field order of codec.py / codec2.py (with
the prediction order), and the per-field modes and prediction modes of train_tables.py (data/traces/tables.pkl).
Output: codemp/netcodec/src/generated/jka_schema.inc (committed; regenerate after a change of the fields or the modes).
The contexts are defined by the C++ code (src/contexts.h) and the tables are trained by the C++ tool netcodec_train
(src/generated/jka_tables.inc).
Run: python gen_netcodec.py"""
import sys, os, pickle, hashlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import codec as C, codec2 as K2

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.normpath(os.path.join(HERE, "..", "..", "data", "traces", "tables.pkl"))
GEN = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "codemp", "netcodec", "src", "generated"))
OUT_SCHEMA = os.path.join(GEN, "jka_schema.inc")

PMODE = {None: "PredMode::kNone", "t": "PredMode::kTime", "pi": "PredMode::kPos", "a2": "PredMode::kAngle"}
CTYPE = {"int": "CType::kInt", "float": "CType::kFloat", "bool": "CType::kBool", "enum": "CType::kEnum"}
NCLS = 19

def main():
    K2.enable_prediction()
    tr = pickle.load(open(TABLES, "rb"))
    modes, pmodes = tr["modes"], tr["pmodes"]
    fields = C.B.bdata.J.FIELDS
    off = {("e:", f["name"]): f["offset"] for f in fields["tables"]["ent"]}
    for tn in ("ps", "pilot", "veh"):
        for f in fields["tables"][tn]: off[("p:", f["name"])] = f["offset"]
    for a in fields["arrays"]:
        for i in range(a["count"]): off[("p:", "%s[%d]" % (a["name"], i))] = a["offset"] + i * a["elem_size"]

    ent = C.EF; pnames = K2.ALLNAMES; pid = {n: i for i, n in enumerate(pnames)}
    pbits = {}
    for t in K2.PS_TABLES.values():
        for n, b in t:
            assert pbits.setdefault(n, b) == b, n
    lines = []; w = lines.append
    w("// Generated by docs_rewrite/netcode/tools/python/gen_netcodec.py: do not edit.")
    w("// Schema (codec field order) of the JKA codec; see docs_rewrite/netcode/progress/step-06-cpp-codec.md.")
    w("")
    def related(pre, name):
        """offsets read by the position prediction of a field, else 0xFFFF"""
        if pmodes.get(pre + name) != "pi": return (0xFFFF, 0xFFFF, 0xFFFF, 0xFFFF)
        i = name[-2]
        if pre == "e:":
            return (off[("e:", "pos.trType")], off[("e:", "pos.trTime")], off[("e:", "pos.trDelta[%s]" % i)], 0)
        return (0xFFFF, off[("p:", "commandTime")], off[("p:", "velocity[%s]" % i)], 1)
    def desc(pre, name, bits, ctx_id):
        cn = pre + name; rel = related(pre, name)
        return ("\t{ .offset = %d, .bits = %d, .ctype = %s, .absolute = %s, .pmode = %s, .ctx = %d, .relType = %d, "
                ".relTime = %d, .relVel = %d, .relKind = %d }, // %s") % (
            off[(pre, name)], bits, CTYPE[C.CTYPE.get(cn, "int")], "true" if modes.get(name, "d") == "a" else "false",
            PMODE[pmodes.get(cn)], ctx_id, rel[0], rel[1], rel[2], rel[3], name)
    w("inline constexpr uint32_t kEntitySize = %d;" % fields["sizeof"]["entityState_t"])
    w("inline constexpr uint32_t kPlayerSize = %d;" % fields["sizeof"]["playerState_t"])
    w("inline constexpr uint32_t kEntityTypeIndex = %d;   // eType, coded apart" % C.ET_IDX)
    w("inline constexpr uint32_t kEntityClasses = %d;" % NCLS)
    w("inline constexpr uint32_t kPlayerNames = %d;" % len(pnames))
    for nm, cname in (("m_iVehicleNum", "kVehicleNum"), ("eFlags", "kPlayerEFlags")):
        w("inline constexpr uint16_t %sOffset = %d;   // bits %d" % (cname, off[("p:", nm)], pbits[nm]))
    w("")
    w("// FieldDesc: offset, bits (0 float, < 0 signed), C type, absolute mode, prediction mode, context row, then for")
    w("// the position prediction the offsets of trType, time, velocity and the kind (0 entity, 1 player state)")
    w("inline constexpr std::array<FieldDesc, %d> kEntityFields{ {" % len(ent))
    for i, (n, b) in enumerate(ent): lines.append(desc("e:", n, b, i))
    w("} };")
    for tab, label in ((0, "kPlayerFields"), (1, "kPilotFields"), (2, "kVehicleFields")):
        w("inline constexpr std::array<FieldDesc, %d> %s{ {" % (len(K2.PS_TABLES[tab]), label))
        for n, b in K2.PS_TABLES[tab]: lines.append(desc("p:", n, b, pid[n]))
        w("} };")
    w("// offsets of every player-state field (union of the three tables): 'has a base' test of the prediction")
    w("inline constexpr std::array<uint16_t, %d> kPlayerAllOffsets{ %s };" % (len(pnames), ", ".join(str(off[("p:", n)]) for n in pnames)))
    w("")
    os.makedirs(GEN, exist_ok=True)
    old = os.path.join(GEN, "jka_codec.inc")
    if os.path.exists(old): os.remove(old)
    text = "\n".join(lines) + "\n"
    open(OUT_SCHEMA, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s, sha1 %s" % (OUT_SCHEMA, hashlib.sha1(text.encode()).hexdigest()[:12]))

if __name__ == "__main__":
    main()
